package dev.aegis.documents.domain.analysis;

import dev.aegis.documents.domain.Subject;
import dev.aegis.documents.domain.analysis.AnalysisTypes.Decision;
import dev.aegis.documents.domain.analysis.AnalysisTypes.Flag;
import dev.aegis.documents.domain.analysis.AnalysisTypes.Status;
import dev.aegis.documents.domain.analysis.AnalysisTypes.Trigger;
import dev.aegis.documents.domain.analysis.AnalysisValues.DocumentDate;
import dev.aegis.documents.domain.analysis.AnalysisValues.GeneratedValues;
import dev.aegis.documents.domain.analysis.AnalysisValues.LabelCandidate;
import dev.aegis.documents.domain.analysis.AnalysisValues.Outcome;
import dev.aegis.documents.domain.analysis.AnalysisValues.SubjectSuggestion;
import dev.aegis.documents.domain.catalog.LabelId;
import dev.aegis.shared.DocumentId;
import dev.aegis.shared.InvalidInputException;
import dev.aegis.shared.MemberId;
import java.time.Instant;
import java.util.ArrayList;
import java.util.EnumSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Optional;
import java.util.Set;

/**
 * Automatic analysis of one document: request generations, the values generated by the latest finished run with
 * their review decisions, the member's filename override and a bounded history of earlier generated values.
 *
 * <p>Invariants: a result is accepted only for the generation that is currently requested, so a late answer of an
 * older run cannot overwrite anything; member decisions (rejected titles, names and subjects, a filename override)
 * survive every later run; the filename override is never touched by a run.
 */
public final class DocumentAnalysis {
    public static final int MAX_HISTORY = 10;
    public static final int MAX_CANDIDATES = 10;
    public static final int MAX_SHORT_TOPIC = 40;

    private final DocumentId documentId;
    private Status status;
    private int generation;
    private Trigger trigger;
    private MemberId requestedBy;
    private Instant requestedAt;
    private String unavailableCode;
    private Instant completedAt;
    private String completedRunRef;
    private String model;
    private int appliedLabels;
    private int suggestedLabels;
    private String title;
    private Decision titleDecision;
    private String titleBefore;
    private DocumentDate documentDate;
    private String shortTopic;
    private LabelId correspondent;
    private Set<Flag> flags;
    private List<LabelCandidate> candidates;
    private List<SubjectSuggestion> subjects;
    private String filenameOverride;
    private MemberId filenameBy;
    private Instant filenameAt;
    private List<GeneratedValues> history;
    private final long version;

    /** Persisted or restored state of an analysis. */
    public record Snapshot(Status status, int generation, Trigger trigger, MemberId requestedBy, Instant requestedAt,
            String unavailableCode, Instant completedAt, String completedRunRef, String model, int appliedLabels,
            int suggestedLabels, String title, Decision titleDecision, String titleBefore, DocumentDate documentDate,
            String shortTopic, LabelId correspondent, Set<Flag> flags, List<LabelCandidate> candidates,
            List<SubjectSuggestion> subjects, String filenameOverride, MemberId filenameBy, Instant filenameAt,
            List<GeneratedValues> history) {
        public Snapshot {
            Objects.requireNonNull(status, "status");
            documentDate = documentDate == null ? DocumentDate.UNKNOWN : documentDate;
            flags = flags == null ? Set.of() : Set.copyOf(flags);
            candidates = candidates == null ? List.of() : List.copyOf(candidates);
            subjects = subjects == null ? List.of() : List.copyOf(subjects);
            history = history == null ? List.of() : List.copyOf(history);
        }
    }

    private DocumentAnalysis(DocumentId documentId, Snapshot snapshot, long version) {
        this.documentId = Objects.requireNonNull(documentId, "document id");
        this.status = snapshot.status();
        this.generation = snapshot.generation();
        this.trigger = snapshot.trigger();
        this.requestedBy = snapshot.requestedBy();
        this.requestedAt = snapshot.requestedAt();
        this.unavailableCode = snapshot.unavailableCode();
        this.completedAt = snapshot.completedAt();
        this.completedRunRef = snapshot.completedRunRef();
        this.model = snapshot.model();
        this.appliedLabels = snapshot.appliedLabels();
        this.suggestedLabels = snapshot.suggestedLabels();
        this.title = snapshot.title();
        this.titleDecision = snapshot.titleDecision();
        this.titleBefore = snapshot.titleBefore();
        this.documentDate = snapshot.documentDate();
        this.shortTopic = snapshot.shortTopic();
        this.correspondent = snapshot.correspondent();
        this.flags = snapshot.flags().isEmpty() ? EnumSet.noneOf(Flag.class) : EnumSet.copyOf(snapshot.flags());
        this.candidates = new ArrayList<>(snapshot.candidates());
        this.subjects = new ArrayList<>(snapshot.subjects());
        this.filenameOverride = snapshot.filenameOverride();
        this.filenameBy = snapshot.filenameBy();
        this.filenameAt = snapshot.filenameAt();
        this.history = new ArrayList<>(snapshot.history());
        this.version = version;
    }

    /** No analysis yet (existing, restored or manually handled documents). */
    public static DocumentAnalysis none(DocumentId documentId) {
        return new DocumentAnalysis(documentId, empty(Status.NOT_REQUESTED, null, null, null), 0);
    }

    /** An uploaded document that is analyzed automatically once its OCR text is archived. */
    public static DocumentAnalysis awaitingArchive(DocumentId documentId, MemberId uploadedBy, Instant now) {
        return new DocumentAnalysis(documentId, empty(Status.AWAITING_ARCHIVE, Trigger.UPLOAD,
                Objects.requireNonNull(uploadedBy), now), 0);
    }

    public static DocumentAnalysis rehydrate(DocumentId documentId, Snapshot snapshot, long version) {
        return new DocumentAnalysis(documentId, snapshot, version);
    }

    private static Snapshot empty(Status status, Trigger trigger, MemberId by, Instant at) {
        return new Snapshot(status, 0, trigger, by, at, null, null, null, null, 0, 0, null, null, null,
                DocumentDate.UNKNOWN, null, null, Set.of(), List.of(), List.of(), null, null, null, List.of());
    }

    // Requests ------------------------------------------------------------------------------------------------------

    /**
     * Starts a new generation. Every request gets a new generation, so an older run's late answer no longer matches.
     *
     * @return the new generation
     */
    public int request(MemberId by, Trigger newTrigger, Instant now) {
        generation++;
        status = Status.REQUESTED;
        trigger = Objects.requireNonNull(newTrigger);
        requestedBy = Objects.requireNonNull(by);
        requestedAt = now;
        unavailableCode = null;
        return generation;
    }

    /** The request could not be handed to the AI boundary; nothing is queued. */
    public void markUnavailable(String code) {
        if (status != Status.REQUESTED) {
            throw new IllegalStateException("analysis of " + documentId + " is not requested");
        }
        status = Status.UNAVAILABLE;
        unavailableCode = Objects.requireNonNull(code);
    }

    /**
     * Takes back a request whose run was cancelled before its result was applied, for example by cancelling a bulk
     * run (issue #115). The document returns to its earlier result or to not requested; the generation stays
     * counted, so a late answer of the cancelled run is refused.
     *
     * @return whether the request of {@code requestedGeneration} was still open
     */
    public boolean withdraw(int requestedGeneration) {
        if (!accepts(requestedGeneration)) {
            return false;
        }
        status = completedAt == null ? Status.NOT_REQUESTED : Status.COMPLETED;
        return true;
    }

    /** Whether a run ever produced a result for this document. */
    public boolean everCompleted() {
        return completedAt != null;
    }

    public boolean awaitsArchive() {
        return status == Status.AWAITING_ARCHIVE;
    }

    /** Whether a result for {@code resultGeneration} may still be applied. */
    public boolean accepts(int resultGeneration) {
        return status == Status.REQUESTED && generation == resultGeneration;
    }

    // Results -------------------------------------------------------------------------------------------------------

    /**
     * Records a finished run. Earlier generated values move to the history; decisions a member made about titles,
     * names and subjects are kept and the same values are not proposed again.
     *
     * @throws IllegalStateException when the generation is no longer current
     */
    public void complete(Outcome outcome) {
        if (!accepts(outcome.generation())) {
            throw new IllegalStateException("analysis generation " + outcome.generation() + " of " + documentId
                    + " is no longer current");
        }
        if (completedAt != null) {
            history.addFirst(new GeneratedValues(generation, completedRunRef, model, completedAt, title,
                    documentDate.value(), shortTopic));
            while (history.size() > MAX_HISTORY) {
                history.removeLast();
            }
        }
        status = Status.COMPLETED;
        completedAt = outcome.completedAt();
        completedRunRef = outcome.runRef();
        model = outcome.model();
        appliedLabels = outcome.appliedLabels();
        suggestedLabels = outcome.suggestedLabels();
        recordTitle(outcome);
        documentDate = outcome.documentDate();
        shortTopic = outcome.shortTopic();
        correspondent = outcome.correspondent();
        flags = outcome.flags().isEmpty() ? EnumSet.noneOf(Flag.class) : EnumSet.copyOf(outcome.flags());
        candidates = mergeCandidates(outcome.candidates());
        subjects = mergeSubjects(outcome.subjects());
    }

    private void recordTitle(Outcome outcome) {
        if (outcome.title() == null || outcome.titleDecision() == null) {
            if (titleDecision == Decision.SUGGESTED) {
                title = null;
                titleDecision = null;
            }
            return;
        }
        boolean rejectedBefore = titleDecision == Decision.REJECTED && outcome.title().equals(title);
        if (rejectedBefore) {
            return;
        }
        title = outcome.title();
        titleDecision = outcome.titleDecision();
        titleBefore = outcome.titleBefore();
    }

    private List<LabelCandidate> mergeCandidates(List<LabelCandidate> proposed) {
        Map<String, LabelCandidate> merged = new LinkedHashMap<>();
        candidates.stream().filter(c -> !c.decision().pending()).forEach(c -> merged.put(c.matchKey(), c));
        for (LabelCandidate candidate : proposed) {
            if (merged.size() >= MAX_CANDIDATES) {
                break;
            }
            merged.putIfAbsent(candidate.matchKey(), candidate);
        }
        return new ArrayList<>(merged.values());
    }

    private List<SubjectSuggestion> mergeSubjects(List<SubjectSuggestion> proposed) {
        Map<Subject, SubjectSuggestion> merged = new LinkedHashMap<>();
        subjects.stream().filter(s -> !s.decision().pending()).forEach(s -> merged.put(s.subject(), s));
        proposed.forEach(s -> merged.putIfAbsent(s.subject(), s));
        return new ArrayList<>(merged.values());
    }

    // Member decisions ----------------------------------------------------------------------------------------------

    /** The generated title the member accepts or reverts; returns it for the document rename. */
    public String decideTitle(boolean accept, MemberId by) {
        Objects.requireNonNull(by);
        if (title == null || titleDecision == null || titleDecision == Decision.ACCEPTED
                || titleDecision == Decision.REJECTED) {
            throw new InvalidInputException("analysis.title.noSuggestion", "There is no generated title to decide on");
        }
        titleDecision = accept ? Decision.ACCEPTED : Decision.REJECTED;
        return accept ? title : titleBefore;
    }

    /** Accepts or rejects a new label name; accepting records the created or reused label. */
    public LabelCandidate decideCandidate(String matchKey, boolean accept, LabelId label, MemberId by, Instant now) {
        for (int i = 0; i < candidates.size(); i++) {
            LabelCandidate candidate = candidates.get(i);
            if (candidate.matchKey().equals(matchKey) && candidate.decision().pending()) {
                LabelCandidate decided = candidate.decided(accept ? Decision.ACCEPTED : Decision.REJECTED,
                        accept ? Objects.requireNonNull(label) : null, by, now);
                candidates.set(i, decided);
                return decided;
            }
        }
        throw new InvalidInputException("analysis.candidate.missing", "There is no pending name suggestion");
    }

    public Optional<LabelCandidate> pendingCandidate(String matchKey) {
        return candidates.stream().filter(c -> c.matchKey().equals(matchKey) && c.decision().pending()).findFirst();
    }

    public SubjectSuggestion decideSubject(Subject subject, boolean accept, MemberId by, Instant now) {
        for (int i = 0; i < subjects.size(); i++) {
            SubjectSuggestion suggestion = subjects.get(i);
            if (suggestion.subject().equals(subject) && suggestion.decision().pending()) {
                SubjectSuggestion decided = suggestion.decided(accept ? Decision.ACCEPTED : Decision.REJECTED, by,
                        now);
                subjects.set(i, decided);
                return decided;
            }
        }
        throw new InvalidInputException("analysis.subject.missing", "There is no pending subject suggestion");
    }

    /** Sets ({@code stem} non-null) or clears the member's filename; runs never change it. */
    public void overrideFilename(String stem, MemberId by, Instant now) {
        filenameOverride = stem;
        filenameBy = stem == null ? null : Objects.requireNonNull(by);
        filenameAt = stem == null ? null : now;
    }

    /** Restores exported analysis values; only while nothing was requested or decided locally. */
    public void restore(Snapshot exported) {
        if (!isPristine()) {
            throw new IllegalStateException("analysis of " + documentId + " is not pristine");
        }
        Status restoredStatus = exported.status() == Status.COMPLETED ? Status.COMPLETED : Status.NOT_REQUESTED;
        DocumentAnalysis restored = new DocumentAnalysis(documentId, exported, version);
        status = restoredStatus;
        generation = restored.generation;
        trigger = restored.trigger;
        requestedBy = restored.requestedBy;
        requestedAt = restored.requestedAt;
        unavailableCode = null;
        completedAt = restored.completedAt;
        completedRunRef = restored.completedRunRef;
        model = restored.model;
        appliedLabels = restored.appliedLabels;
        suggestedLabels = restored.suggestedLabels;
        title = restored.title;
        titleDecision = restored.titleDecision;
        titleBefore = restored.titleBefore;
        documentDate = restored.documentDate;
        shortTopic = restored.shortTopic;
        correspondent = restored.correspondent;
        flags = restored.flags;
        candidates = restored.candidates;
        subjects = restored.subjects;
        filenameOverride = restored.filenameOverride;
        filenameBy = restored.filenameBy;
        filenameAt = restored.filenameAt;
        history = restored.history;
    }

    public boolean isPristine() {
        return (status == Status.NOT_REQUESTED || status == Status.AWAITING_ARCHIVE) && generation == 0
                && filenameOverride == null && completedAt == null;
    }

    /** Whether a finished result still waits for a member (suggested title, names or subjects). */
    public boolean hasPendingSuggestions() {
        return titleDecision == Decision.SUGGESTED || candidates.stream().anyMatch(c -> c.decision().pending())
                || subjects.stream().anyMatch(s -> s.decision().pending());
    }

    public Snapshot snapshot() {
        return new Snapshot(status, generation, trigger, requestedBy, requestedAt, unavailableCode, completedAt,
                completedRunRef, model, appliedLabels, suggestedLabels, title, titleDecision, titleBefore,
                documentDate, shortTopic, correspondent, flags, candidates, subjects, filenameOverride, filenameBy,
                filenameAt, history);
    }

    public DocumentId documentId() {
        return documentId;
    }

    public Status status() {
        return status;
    }

    public int generation() {
        return generation;
    }

    public Optional<String> filenameOverride() {
        return Optional.ofNullable(filenameOverride);
    }

    public DocumentDate documentDate() {
        return documentDate;
    }

    public Optional<String> shortTopic() {
        return Optional.ofNullable(shortTopic);
    }

    public Optional<LabelId> correspondent() {
        return Optional.ofNullable(correspondent);
    }

    public Set<Flag> flags() {
        return Set.copyOf(flags);
    }

    public Optional<String> title() {
        return Optional.ofNullable(title);
    }

    public Optional<Decision> titleDecision() {
        return Optional.ofNullable(titleDecision);
    }

    public List<LabelCandidate> candidates() {
        return List.copyOf(candidates);
    }

    public List<SubjectSuggestion> subjects() {
        return List.copyOf(subjects);
    }

    public long version() {
        return version;
    }
}
